/// Location of the generated bindings, relative to this crate.
pub const BINDINGS_PATH: &str = "../src/shared/ipc/bindings.ts";

/// Upper bound for saving on exit; after it the app quits anyway (data stays in the WAL/queue).
const SHUTDOWN_TIMEOUT: Duration = Duration::from_secs(10);

/// The IPC surface: every command and event exported to TypeScript.
#[must_use]
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::app_info,
            commands::campaign_create::<tauri::Wry>,
            commands::campaign_open::<tauri::Wry>,
            commands::campaign_restore_backup,
            commands::campaign_close,
            commands::campaign_checkpoint,
            commands::campaign_current,
            commands::get_snapshot,
            commands::submit_intent::<tauri::Wry>,
            commands::logs_recent,
            commands::log_frontend,
            updater::update_check::<tauri::Wry>,
            updater::update_install::<tauri::Wry>,
        ])
        .events(collect_events![
            GameEventsEmitted,
            logging::LogRecord,
            updater::UpdateAvailable
        ])
        .typ::<dnd_protocol::ServerMessage>()
}

/// Writes `bindings.ts` (called from the `export_bindings` test; CI checks it is up to date).
pub fn export_bindings(path: &std::path::Path) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default().header(
                "// Generated by `cargo test -p dnd-desktop export_bindings`. Do not edit.\n/* eslint-disable */",
            ),
            path,
        )
        .map_err(|e| e.to_string())
}

/// Keeps the log writer alive; taken (and thereby flushed) on shutdown.
struct LogGuard(StdMutex<Option<WorkerGuard>>);

/// Starts the application.
pub fn run() -> Result<(), tauri::Error> {
    let builder = specta_builder();

    let app = tauri::Builder::default()
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.set_focus();
            }
        }))
        .plugin(tauri_plugin_window_state::Builder::default().build())
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);

            let log_dir = app.path().app_log_dir()?;
            let (guard, logs) = logging::init(&log_dir)?;
            let handle = app.handle().clone();
            logs.set_sink(move |record| {
                let _ = record.clone().emit(&handle);
            });
            app.manage(LogGuard(StdMutex::new(Some(guard))));
            tracing::info!(version = env!("CARGO_PKG_VERSION"), log_dir = %log_dir.display(), "DndStudio started");

            let state = AppState::new(logs);
            tauri::async_runtime::spawn(autosave::run(state.server.clone()));
            app.manage(state);

            app.manage(updater::PendingUpdate::default());
            if updater::is_configured(app.handle()) {
                app.handle()
                    .plugin(tauri_plugin_updater::Builder::new().build())?;
            }
            tauri::async_runtime::spawn(updater::run(app.handle().clone()));
            Ok(())
        })
        .build(tauri::generate_context!())?;

    let shutting_down = AtomicBool::new(false);
    app.run(move |handle, event| {
        if let RunEvent::ExitRequested { api, .. } = event {
            // First request: keep the process alive until the campaign is saved, then exit again.
            if !shutting_down.swap(true, Ordering::SeqCst) {
                api.prevent_exit();
                let handle = handle.clone();
                tauri::async_runtime::spawn(async move {
                    shutdown(&handle).await;
                    handle.exit(0);
                });
            }
        }
    });
    Ok(())
}

/// Graceful shutdown (CLAUDE.md §10): checkpoint and close the campaign, flush logs.
/// (Game data is already on disk: persistence is write-through, ADR-0014.)
async fn shutdown(app: &tauri::AppHandle) {
    let state = app.state::<AppState>();
    let close = async {
        if let Some(server) = state.server.lock().await.take() {
            server.close().await
        } else {
            Ok(())
        }
    };
    match tokio::time::timeout(SHUTDOWN_TIMEOUT, close).await {
        Ok(Ok(())) => tracing::info!("shut down cleanly"),
        Ok(Err(e)) => tracing::error!(error = %e, "failed to save on exit"),
        Err(_) => tracing::error!("saving on exit timed out"),
    }
    if let Ok(mut guard) = app.state::<LogGuard>().0.lock() {
        guard.take();
    }
}
