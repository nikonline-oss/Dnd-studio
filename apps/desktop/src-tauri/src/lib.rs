//! DndStudio desktop client: Tauri shell, local in-process server and typed IPC.

mod commands;
mod error;
mod local_server;

pub use commands::{AppInfo, AppState, GameEventsEmitted};
pub use error::{IpcError, IpcErrorKind};
pub use local_server::{CampaignInfo, IntentOutcome, LocalServer, folder_name};

use tauri::Manager;
use tauri_specta::{Builder, collect_commands, collect_events};

/// Location of the generated bindings, relative to this crate.
pub const BINDINGS_PATH: &str = "../src/shared/ipc/bindings.ts";

/// The IPC surface: every command and event exported to TypeScript.
#[must_use]
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::app_info,
            commands::campaign_create::<tauri::Wry>,
            commands::campaign_open::<tauri::Wry>,
            commands::campaign_close,
            commands::campaign_current,
            commands::get_snapshot,
            commands::submit_intent::<tauri::Wry>,
        ])
        .events(collect_events![GameEventsEmitted])
        .typ::<dnd_protocol::ServerMessage>()
}

/// Writes `bindings.ts` (called from the `export_bindings` test; CI checks it is up to date).
pub fn export_bindings(path: &std::path::Path) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// Generated by `cargo test -p dnd-desktop export_bindings`. Do not edit.\n/* eslint-disable */"),
            path,
        )
        .map_err(|e| e.to_string())
}

/// Starts the application.
pub fn run() -> Result<(), tauri::Error> {
    let builder = specta_builder();

    tauri::Builder::default()
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.set_focus();
            }
        }))
        .plugin(tauri_plugin_window_state::Builder::default().build())
        .plugin(tauri_plugin_dialog::init())
        .manage(AppState::default())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .run(tauri::generate_context!())
}
